class datatype {
    public static void main(String[] args) {
        // Integer data type
        int num = 10;
        System.out.println("Integer: " + num);

        // Double data type
        double decimalNum = 10.5;
        System.out.println("Double: " + decimalNum);

        // Character data type
        char letter = 'A';
        System.out.println("Character: " + letter);

        // Boolean data type
        boolean isTrue = true;
        System.out.println("Boolean: " + isTrue);

        // String data type
        String text = "Hello, World!";
        System.out.println("String: " + text);

        //byte data types
        byte smallNum = 100;
        System.out.println("Byte: " + smallNum);

        //float data types
        float floatNum = 5.75f;
        System.out.println("Float: " + floatNum);

        //Boolean data types
        boolean isFalse = false;
        System.out.println("Boolean: " + isFalse);

        //Ascii value addition
        char char1 = 'A';
        char char2 = 'B';
        int asciiSum = char1 + char2;
        System.out.println("Sum of ASCII values of " + char1 + " and " + char2 + ": " + (char)(asciiSum));
    }
} 